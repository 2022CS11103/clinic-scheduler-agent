"""Versioned scheduling policy.

Every rule is a constraint, and true is the stricter side. The applier
rejects patches that weaken a rule or that use an operation other than
set_rule / remove_tool. A patch cannot add tools or execute code.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
V0_PATH = ROOT / "policies" / "v0.json"
V1_PATH = ROOT / "policies" / "v1.json"

# Name-only lookup returns appointments without proof of identity.
DANGEROUS_TOOLS = {"find_patient_by_name"}


class PolicyError(Exception):
    pass


def load_policy(path: str | Path | None = None) -> dict:
    policy_path = Path(path) if path else V0_PATH
    with policy_path.open(encoding="utf-8") as handle:
        data = json.load(handle)
    validate_policy(data)
    return data


def validate_policy(data: dict) -> None:
    if not isinstance(data, dict):
        raise PolicyError("policy must be an object")
    for key in ("version", "rules", "tools_allowed"):
        if key not in data:
            raise PolicyError(f"policy missing {key}")
    if not isinstance(data["version"], int):
        raise PolicyError("version must be an int")
    if not isinstance(data["rules"], dict) or not data["rules"]:
        raise PolicyError("rules must be a non-empty object")
    for name, value in data["rules"].items():
        if not isinstance(value, bool):
            raise PolicyError(f"rule {name} must be boolean so it cannot carry hidden instructions")
    if not isinstance(data["tools_allowed"], list) or not all(
        isinstance(item, str) for item in data["tools_allowed"]
    ):
        raise PolicyError("tools_allowed must be a list of strings")


def apply_patch(policy: dict, patch: dict) -> dict:
    """Return a new policy. Does not mutate the baseline."""
    validate_policy(policy)
    if patch.get("changes") is None or not isinstance(patch["changes"], list):
        raise PolicyError("patch.changes must be a list")

    updated = copy.deepcopy(policy)
    for change in patch["changes"]:
        if not isinstance(change, dict) or "op" not in change:
            raise PolicyError("each change needs an op")
        op = change["op"]
        if op == "set_rule":
            rule = change.get("rule")
            value = change.get("value")
            if rule not in updated["rules"]:
                raise PolicyError(f"unknown rule {rule}")
            if not isinstance(value, bool):
                raise PolicyError(f"rule {rule} must stay boolean")
            if updated["rules"][rule] is True and value is False:
                raise PolicyError(f"refusing to weaken rule {rule}")
            updated["rules"][rule] = value
        elif op == "remove_tool":
            tool = change.get("tool")
            if not isinstance(tool, str):
                raise PolicyError("remove_tool needs a tool name")
            updated["tools_allowed"] = [item for item in updated["tools_allowed"] if item != tool]
        else:
            # No add_tool, no prompt rewrite, no arbitrary code.
            raise PolicyError(f"unsupported patch op {op}")

    if updated["rules"].get("verify_before_phi"):
        updated["tools_allowed"] = [
            item for item in updated["tools_allowed"] if item not in DANGEROUS_TOOLS
        ]

    updated["version"] = int(policy["version"]) + 1
    updated["notes"] = (
        "Generated by the eval loop from failed checks. "
        "Constraints only move toward stricter."
    )
    validate_policy(updated)
    return updated


def save_policy(policy: dict, path: str | Path) -> None:
    validate_policy(policy)
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", encoding="utf-8") as handle:
        json.dump(policy, handle, indent=2)
        handle.write("\n")
